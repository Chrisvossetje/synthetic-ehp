//! Serialization of the computed spectral sequence to disk: the website's
//! TypeScript data files (`write_typescript_file`), the replayable action logs
//! (`write_log`), and a LaTeX-style order table (`export_order_table`).

use std::{
    collections::{BTreeMap, HashMap}, fs::File, io::{self, Write}, path::{Path, PathBuf}
};

use itertools::Itertools;
use serde::{Deserialize, Serialize};

use crate::{
    MAX_EXPORT_STEM, MAX_STEM, data::curtis::MODEL, domain::{e1::E1, model::SyntheticSS, process::compute_pages}, solve::{action::Action, proof::compact_proof_text}, types::{Generator, Kind, Torsion}
};

pub fn write_vec_to_file<T: std::fmt::Debug>(vec: &[T], path: &str) -> io::Result<()> {
    let mut file = File::create(path)?;

    for item in vec {
        writeln!(file, "{item:?}")?;
    }

    Ok(())
}

pub fn repo_root_path(file_name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join(file_name)
}

/// Export EHP and AHSS tag prefixes separately from spectral-sequence identities.
pub fn write_tag_translation(
    translations: &BTreeMap<String, String>,
    stable_translations: &BTreeMap<String, String>,
) -> io::Result<()> {
    let mut file = File::create(repo_root_path("site/src/tag_translation.ts"))?;
    writeln!(file, "// Generated by logic::routines::export_tag_translation; do not edit by hand.")?;
    writeln!(file, "// Keys are Curtis tags without the final sphere bracket.")?;
    writeln!(file, "export const TAG_TRANSLATIONS: Readonly<Record<string, string>> = {};",
        serde_json::to_string_pretty(translations)?)?;
    writeln!(file, "\n// AHSS tags name stable AEHP elements directly.")?;
    writeln!(file, "export const STABLE_TAG_TRANSLATIONS: Readonly<Record<string, string>> = {};",
        serde_json::to_string_pretty(stable_translations)?)?;
    Ok(())
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Differential {
    pub from: String,
    pub to: String,

    pub d: i32,

    #[serde(skip_serializing_if = "Option::is_none")]
    pub proof: Option<String>,

    pub kind: Kind,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct InternalTauMult {
    pub from: String,
    pub to: String,
    pub page: i32,

    #[serde(skip_serializing_if = "Option::is_none")]
    pub proof: Option<String>,

    pub kind: Kind,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ExternalTauMult {
    pub from: String,
    pub to: String,

    pub af: i32,

    #[serde(skip_serializing_if = "Option::is_none")]
    pub proof: Option<String>,

    pub kind: Kind,
}

#[allow(dead_code)]
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Multiplication {
    pub from: String,
    pub to: String,
    pub internal: bool,
    pub kind: String,
}

pub fn write_typescript_file(
    output_path: &str,
    data_name: &str,
    data: &SyntheticSS,
    model: &E1,
) -> Result<(), std::io::Error> {
    let mut file = File::create(output_path)?;

    let mut data = data.clone();
    // add_final_diagonal would mutate the model too; skipped under new design
    let mut model = model.clone();

    for (index, torsion) in data.generators.iter().enumerate() {
        model.get_mut(index).torsion = *torsion;
        if let Some(names) = data.induced_name.as_ref()
            .and_then(|all_names| all_names.get(index))
            .filter(|names| !names.is_empty())
        {
            model.get_mut(index).induced_name = names.clone();
        }
    }

    add_final_diagonal(&mut model, &mut data);

    // Serialize generators to JSON strings
    let gens: Vec<String> = model
        .gens()
        .iter().enumerate()
        .filter_map(|(index, g)| if g.stem <= MAX_EXPORT_STEM || (g.stem == MAX_EXPORT_STEM + 1 && data.out_diffs[index].len() > 0) {
            Some(serde_json::to_string(g).unwrap())
        } else { None })
        .collect();

    // Differentials, internal and external tau-multiplications are all stored
    // together in `from_to`; we recover which is which from the bidegree shift.
    let mut differentials = vec![];
    let mut int_tau_mults = vec![];
    let mut ext_tau_mults = vec![];
    let ext_tau_metadata: HashMap<_, _> = data.external_taus().enumerate()
        .map(|(order, tau)| ((model.name(tau.from), model.name(tau.to)), (tau.af, order)))
        .collect();

    for ((from, to), (kind, p)) in &data.from_to {
        let d_y = model.y(*from) - model.y(*to);
        let d_stem = model.stem(*from) - model.stem(*to);
        if model.get(*to).stem > MAX_EXPORT_STEM {
            continue;
        }
        // Logs retain the complete derivation; the website gets the compact chain.
        let proof = p.as_deref().map(compact_proof_text).map(str::to_owned);
        if d_y == 0 {
            int_tau_mults.push(InternalTauMult {
                from: model.name(*from).to_string(),
                to: model.name(*to).to_string(),
                kind: *kind,
                proof,
                page: 2, // TODO : This is not generic enough but good enough for our range
            });
        } else if d_stem == 0 {
            ext_tau_mults.push(ExternalTauMult {
                from: model.name(*from).to_string(),
                to: model.name(*to).to_string(),
                af: ext_tau_metadata.get(&(model.name(*from), model.name(*to)))
                    .map(|&(af, _)| af).unwrap_or(0),
                kind: *kind,
                proof,
            });
        } else {
            differentials.push(Differential {
                from: model.name(*from).to_string(),
                to: model.name(*to).to_string(),
                d: model.y(*from) - model.y(*to),
                kind: *kind,
                proof,
            });
        }
    }

    // Preserve Rust's application order, including insertion order within ties.
    ext_tau_mults.sort_by_key(|tau| ext_tau_metadata.get(&(tau.from.as_str(), tau.to.as_str()))
        .map(|&(_, order)| order).unwrap_or(usize::MAX));

    // Serialize differentials to JSON strings
    let diffs: Vec<String> = differentials
        .iter()
        .map(|d| serde_json::to_string(d).unwrap())
        .collect();

    let int_tau_mults: Vec<String> = int_tau_mults
        .iter()
        .map(|m| serde_json::to_string(m).unwrap())
        .collect();

    let ext_tau_mults: Vec<String> = ext_tau_mults
        .iter()
        .map(|m| serde_json::to_string(m).unwrap())
        .collect();

    let mults: Vec<String> = vec![];

    let pre = format!(
        "// @ts-nocheck\n\
         // This file has been generated by curtis.rs\n\
         // Based on curtis tables of the AEHP sequence\n\
         import {{ SyntheticEHP }} from \"./types\";\n\n\
         export const MAX_STEM{} = {};\n\n\
         export const data{}: SyntheticEHP = {{\n\
         \x20   \"generators\": [\n",
        data_name.to_uppercase(),
        MAX_EXPORT_STEM,
        data_name
    );

    let ds = "\n    ],\n    \"differentials\": [\n";
    let ms = "\n    ],\n    \"multiplications\": [\n";
    let its = "\n    ],\n    \"internal_tau_mults\": [\n";
    let ets = "\n    ],\n    \"external_tau_mults\": [\n";
    let post = "    ]\n}";

    file.write_all(pre.as_bytes())?;
    file.write_all(gens.join(",\n").as_bytes())?;
    file.write_all(ds.as_bytes())?;
    file.write_all(diffs.join(",\n").as_bytes())?;
    file.write_all(ms.as_bytes())?;
    file.write_all(mults.join(",\n").as_bytes())?;
    file.write_all(its.as_bytes())?;
    file.write_all(int_tau_mults.join(",\n").as_bytes())?;
    file.write_all(ets.as_bytes())?;
    file.write_all(ext_tau_mults.join(",\n").as_bytes())?;
    file.write_all(post.as_bytes())?;

    Ok(())
}

pub fn write_all(data: &SyntheticSS, model: &E1, log: &Vec<Action>, ahss: bool) {
    let log = log.iter().unique().map(|x| x.clone()).collect();
    if ahss {
        write_typescript_file("../site/src/data_stable.ts", "_stable", &data, model).unwrap();
        write_log(&log, ahss).unwrap();
    } else {
        write_typescript_file("../site/src/data.ts", "", &data, model).unwrap();
        write_log(&log, ahss).unwrap();
    }
}

pub fn write_log(log: &Vec<Action>, ahss: bool) -> io::Result<()> {
    let name = if ahss { "log_stable" } else { "log" };

    write_vec_to_file(&log, &format!("../{}.txt", name))?;
    let mut file = File::create(&format!("../{}.json", name))?;
    writeln!(file, "{}", serde_json::to_string(log)?)?;
    file.flush().unwrap();
    Ok(())
}


